#include <iostream>
using namespace std;

int main() {
    // Включаем поддержку русского языка в консоли
    setlocale(LC_ALL, "Russian");

    int sum = 0; // Переменная для хранения суммы, изначально равна 0

    cout << "Вычисление суммы целых положительных четных чисел, меньших 100" << endl;
    cout << "-------------------------------------------------------------" << endl;

    // Цикл с параметром. 
    // Начинаем с 2 (первое положительное четное число). 
    // Условие: i < 100 (строго меньше). 
    // Шаг: i += 2 (увеличиваем на 2, чтобы перебирать только четные).
    for (int i = 2; i < 100; i += 2) {
        sum += i; // Добавляем текущее число к общей сумме
    }

    // Вывод результата с заголовком
    cout << "Сумма целых положительных четных чисел < 100 равна: " << sum << endl;

    return 0;
}